import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import path from 'node:path';
import {PIN,adaptWorker,adaptRouter,adaptRefresh,adaptDispatcher} from './install-mac-profile-on-windows.mjs';
const root=process.cwd(),source=path.resolve(process.argv[2]||root);
const normalize=text=>text.replace(/\r\n/g,'\n');
const worker=normalize(await readFile(path.join(source,'codex-profile/mac/hooks/graph_skill_index.py'),'utf8'));
const native=adaptWorker(worker);
const section=(text,start,end)=>text.slice(text.indexOf(start),text.indexOf(end,text.indexOf(start)));
assert.equal(section(native,'def catalog_rows(', 'class _WorkerHandler'),section(worker,'def catalog_rows(', 'class _WorkerHandler'));
assert.equal(section(native,'def _query_process(', 'class _ProcessGraphWorker'),section(worker,'def _query_process(', 'class _ProcessGraphWorker'));
assert.equal(section(native,'    def _finished(', 'def serve('),section(worker,'    def _finished(', 'def serve('));
assert(native.includes('warm_barrier.wait(timeout=180)'));
assert(native.includes('Not every retrieval process completed warm-up'));
assert(native.includes('Worker authentication failed'));assert(native.includes('socketserver.TCPServer'));
const router=normalize(await readFile(path.join(source,'codex-profile/.codex/hooks/skill-router.mjs'),'utf8'));
const adapted=adaptRouter(router);
assert.equal(section(adapted,'function queryTokens(', 'async function requestAfterWorkerStart('),section(router,'function queryTokens(', 'function workerSocketPath('));
assert.equal(adapted.slice(adapted.indexOf('function promptSkillExclusions(')),router.slice(router.indexOf('function promptSkillExclusions(')).replaceAll('"graph-tool-call-venv", "bin", "python"','"graph-tool-call-windows", "Scripts", "python.exe"'));
assert.equal(adapted.split('\n')[0],'#!/usr/bin/env node');
const refresh=adaptRefresh(await readFile(path.join(source,'codex-profile/mac/hooks/refresh-skill-registry.mjs'),'utf8'));
assert(refresh.includes('SENTENCE_TRANSFORMERS_HOME'));assert(refresh.includes('!server.disabled'));
const dispatch=adaptDispatcher(await readFile(path.join(source,'codex-profile/.codex/hooks/hook-dispatch.mjs'),'utf8'));
assert(!dispatch.includes('E:\\\\能力归纳概括'));
assert.throws(()=>adaptRouter('not the pinned source'));
console.log(JSON.stringify({baselineCommit:PIN,comparisonSource:source,workerPolicyPreservedAcrossPlatforms:true,routerPolicyPreservedAcrossPlatforms:true,windowsBindingsAndEagerWarmup:true,sourceMismatchRejected:true}));
