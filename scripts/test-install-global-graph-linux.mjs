import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir, mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { install, linuxContext, linuxMcpPreset, serviceText, unifiedAgents } from './install-global-graph-linux.mjs';

const home = await mkdtemp(path.join(os.tmpdir(), 'global-graph-linux-'));
try {
  const root = path.join(home, '.codex');
  await mkdir(path.join(root, 'hooks'), { recursive: true });
  await mkdir(path.join(root, 'skill-registry'));
  const original = '# preserved\nmodel = "fixture"\n[features]\ncode_mode = true\n[hooks.UserPromptSubmit."0"]\ntrusted_hash = "fixture-do-not-change"\n';
  await writeFile(path.join(root, 'config.toml'), original);
  const dispatcher = await readFile(new URL('../codex-profile/.codex/hooks/hook-dispatch.mjs', import.meta.url), 'utf8');
  await writeFile(path.join(root, 'hooks/hook-dispatch.mjs'), dispatcher.replace('own("skill-router", 60000)', 'own("skill-router", 12000)'));
  const canonical = await readFile(new URL('../codex-profile/mac/hooks/context-refresh.mjs', import.meta.url), 'utf8');
  const old = '#!/usr/bin/env node\nimport { readFile } from "node:fs/promises";\nconst batchingContract = "preserve-custom-rule";\nconst codexRoot="fixture";const input={};const eventName="UserPromptSubmit";\nconst parts = [];\n';
  await writeFile(path.join(root, 'hooks/context-refresh.mjs'), old);
  const hooks = { hooks: { UserPromptSubmit: [{ hooks: [{ command: 'node hook-dispatch.mjs', timeout: 20 }] }] }, custom: 'preserve' };
  await writeFile(path.join(root, 'hooks.json'), JSON.stringify(hooks));
  await writeFile(path.join(root, 'skill-registry/routing-rules.json'), '{"custom":["keep"]}');
  assert.equal(linuxContext(linuxContext(old, canonical), canonical), linuxContext(old, canonical));
  assert.ok(linuxContext(old, canonical).includes('preserve-custom-rule'));
  assert.throws(() => serviceText(home, 21), /1-20/);
  assert.ok(serviceText(home, 8).includes('StartLimitIntervalSec=0'), 'persistent service must not permanently stop after a short failure burst');
  assert.ok(serviceText(home, 8).includes('MemoryHigh=22G\nMemoryMax=24G'), 'graph hot reload needs measured headroom without raising the hard cap');
  const preset = '[features]\nmulti_agent = true\n[mcp_servers.task_tree]\ncommand = "/usr/bin/node"\nargs = ["old-project-stub.mjs"]\n[mcp_servers.other]\ncommand = "keep"\n';
  const portable = linuxMcpPreset(preset, home);
  assert.ok(portable.includes('.codex/tools/llm-task-tree-kit/scripts/mcp-server.mjs'));
  assert.ok(portable.includes('[mcp_servers.other]\ncommand = "keep"'));
  assert.equal(linuxMcpPreset(portable, home), portable);
  const checked = await install({ home, apply: false });
  assert.ok(checked.changes.length > 5);
  assert.equal(await readFile(path.join(root, 'config.toml'), 'utf8'), original);
  await install({ home, apply: true, processes: 8 });
  const second = await install({ home, apply: false, processes: 8 });
  assert.deepEqual(second.changes, []);
  const changed = await readFile(path.join(root, 'config.toml'), 'utf8');
  assert.ok(changed.includes('trusted_hash = "fixture-do-not-change"'));
  assert.ok(changed.includes('code_mode = true'));
  assert.ok(changed.includes('max_concurrent_threads_per_session = 20'));
  const output = JSON.parse(await readFile(path.join(root, 'hooks.json'), 'utf8'));
  assert.equal(output.custom, 'preserve');
  assert.equal(output.hooks.UserPromptSubmit[0].hooks[0].timeout, 65);
  assert.equal(JSON.parse(await readFile(path.join(root, 'skill-registry/external-library-config.json'), 'utf8')).requireComplete, true);
  assert.equal(spawnSync(process.execPath, ['--check', path.join(root, 'hooks/context-refresh.mjs')]).status, 0);
  const begin = '<!-- ai-engineering-governance-template:begin -->';
  const end = '<!-- ai-engineering-governance-template:end -->';
  const oldBody = '# Global Codex Instructions\n\nOld generated execution policy.';
  assert.equal(unifiedAgents(`${oldBody}\n\n${begin}\n${oldBody}\n${end}\n`, 'new'), `${begin}\nnew\n${end}\n`);
  assert.ok(unifiedAgents(`CUSTOM BEFORE\n${begin}\nold\n${end}\nCUSTOM AFTER`, 'new').includes('CUSTOM BEFORE'));
  assert.ok(unifiedAgents(`CUSTOM BEFORE\n${begin}\nold\n${end}\nCUSTOM AFTER`, 'new').endsWith('CUSTOM AFTER\n'));
  assert.throws(() => unifiedAgents('unmarked custom instructions', 'new'), /Unrecognized/);
  await writeFile(path.join(root, 'AGENTS.md'), `${oldBody}\n\n${begin}\n${oldBody}\n${end}\n`);
  const customSkill = path.join(home, '.agents/skills/user-private');
  await mkdir(customSkill, { recursive: true });
  await writeFile(path.join(customSkill, 'SKILL.md'), 'keep user Skill');
  const promptPath = path.join(root, 'prompts/global-methodology-source.zh.md');
  await mkdir(path.dirname(promptPath), { recursive: true });
  await writeFile(promptPath, 'old user source');
  assert.ok((await install({ home, unifyMethodology: true })).changes.includes('.codex/prompts/global-methodology-source.zh.md'));
  assert.equal(await readFile(promptPath, 'utf8'), 'old user source', 'check must not publish');
  const unified = await install({ home, apply: true, unifyMethodology: true });
  assert.equal(await readFile(path.join(unified.backup, '.codex/prompts/global-methodology-source.zh.md'), 'utf8'), 'old user source');
  const targetConfig = JSON.parse(await readFile(path.join(root, 'prompt-publisher/methodology-targets.json'), 'utf8'));
  assert.ok(targetConfig.routes.filter(x => x.skillFile).every(x => x.skillFile.startsWith('../../.agents/skills/')));
  assert.ok((await readFile(path.join(root, 'hooks/context-refresh.mjs'), 'utf8')).includes('ADAPTIVE_TOOL_SCHEDULING_CONTRACT_V5'));
  assert.equal(await readFile(path.join(customSkill, 'SKILL.md'), 'utf8'), 'keep user Skill');
  assert.ok((await readFile(path.join(root, 'config.toml'), 'utf8')).includes('trusted_hash = "fixture-do-not-change"'));
  assert.deepEqual((await install({ home, unifyMethodology: true })).changes, [], 'unification must be idempotent');
  console.log('Linux graph migration: dry-run, preservation, cadence, timeout, pool bounds and idempotence passed');
} finally {
  await rm(home, { recursive: true, force: true });
}
