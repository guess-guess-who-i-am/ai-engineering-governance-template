import assert from 'node:assert/strict';
import { mkdtemp, readFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { WebSearchEvidence } from './web-search-evidence.mjs';

const raw = item => ({ at: 1, method: 'rawResponseItem/completed', params: { item } });
const completed = item => ({ at: 2, method: 'item/completed', params: { item } });
const folder = await mkdtemp(path.join(os.tmpdir(), 'web-evidence-'));
const audit = new WebSearchEvidence();
audit.observe(completed({ type: 'webSearch', id: 'native', action: { type: 'search', queries: ['one', 'two'] }, results: null }));
audit.observe(raw({ type: 'function_call', namespace: 'web', name: 'run', call_id: '../untrusted-id', arguments: JSON.stringify({ search_query: [{ q: 'one' }, { q: 'two' }] }) }));
const results = [{ type: 'text_result', ref_id: 'r1', url: 'https://example.com/a', snippet: '摘要', future_field: { retained: true } }];
audit.observe(completed({ type: 'webSearch', id: '../untrusted-id', action: { type: 'search' }, results }));
const text = '完整工具输出\n' + '正文'.repeat(50000);
audit.observe(raw({ type: 'function_call_output', call_id: '../untrusted-id', output: [{ type: 'input_text', text }] }));
audit.observe(completed({ type: 'webSearch', id: 'empty', action: { type: 'search' }, results: [] }));
const summary = await audit.save(folder);
const native = summary.calls.find(c => c.callId === 'native');
assert.equal(native.structuredResultCount, null, 'missing is not zero');
assert.equal(native.modelOutput.characters, null);
assert.equal(native.coverage, 'unavailable');
const observed = summary.calls.find(c => c.callId === '../untrusted-id');
assert.equal(observed.structuredResultCount, 1);
assert.equal(observed.uniqueResultUrls.length, 1);
assert.equal(observed.modelOutput.characters, Array.from(text).length);
assert.equal(await readFile(path.join(folder, observed.modelOutput.artifact), 'utf8'), text, 'never clip the stored tool output');
assert.deepEqual(JSON.parse(await readFile(path.join(folder, observed.structuredResultsArtifact), 'utf8')), results);
assert.equal(observed.recorderTruncated, false);
assert.equal(observed.upstreamTruncated, 'unknown', 'a missing truncation flag is not false');
assert.equal(observed.modelConsumedAll, 'unknown', 'a tool output is not proof of model consumption');
assert.equal(summary.calls.find(c => c.callId === 'empty').structuredResultCount, 0);
assert.equal(summary.complete, false, 'one good call cannot conceal another missing call');
assert.equal(observed.modelOutput.artifact.includes('..'), false, 'provider IDs cannot escape the evidence folder');

const explicit = new WebSearchEvidence();
explicit.observe(completed({ type: 'webSearch', id: 'cut', action: { type: 'openPage', url: 'https://example.com' }, results: [{ truncated: true }] }));
assert.equal((await explicit.save(await mkdtemp(path.join(os.tmpdir(), 'web-cut-')))).calls[0].upstreamTruncated, true);
const custom = new WebSearchEvidence();
custom.observe(raw({ type: 'custom_tool_call', namespace: 'web', name: 'run', call_id: 'custom', input: '{"search_query":[{"q":"custom-query"}]}' }));
const customText = '真实定制工具输出\n【turn0search0】 [wordlim: 200]\n【turn0search1】 [wordlim: 200]';
custom.observe(raw({ type: 'custom_tool_call_output', call_id: 'custom', output: customText }));
const customCall = (await custom.save(await mkdtemp(path.join(os.tmpdir(), 'web-custom-')))).calls[0];
assert.deepEqual(customCall.queries, ['custom-query']);
assert.equal(customCall.modelOutput.characters, Array.from(customText).length);
assert.equal(customCall.listedReferenceCount, 2);
assert.equal(customCall.structuredResultCount, null, 'text references must not be misreported as provider result count');
assert.equal(customCall.coverage, 'output-only');
const privateEvent = audit.safeEvent(raw({ type: 'reasoning', id: 'reasoning', encrypted_content: 'private', summary: 'not needed' }));
assert.equal(JSON.stringify(privateEvent).includes('private'), false);
assert.equal(JSON.stringify(privateEvent).includes('not needed'), false);
const outputEvent = audit.safeEvent(raw({ type: 'function_call_output', call_id: '../untrusted-id', output: [{ type: 'input_text', text }] }));
assert.equal(outputEvent.params.item.output[0].text, text);
const wrapped = new WebSearchEvidence();
wrapped.observe(raw({type:'custom_tool_call',name:'exec',call_id:'envelope',input:'tools.web.run(...)'}));
wrapped.observe({at:1,method:'item/started',params:{item:{type:'webSearch',id:'inner'}}});
wrapped.observe(completed({type:'webSearch',id:'inner',results:null,action:{type:'search',queries:['question']}}));
wrapped.observe(raw({type:'custom_tool_call_output',call_id:'envelope',output:'shared body\n【turn0search0】 [wordlim: 200]'}));
const wrappedSummary=await wrapped.save(await mkdtemp(path.join(os.tmpdir(),'web-envelope-')));
assert.equal(wrappedSummary.envelopes.length,1);
assert.deepEqual(wrappedSummary.calls[0].modelFacingEnvelopeIds,['envelope']);
assert.equal(wrappedSummary.calls[0].listedReferenceCount,null,'do not assign shared sources to one inner call');
assert.equal(wrappedSummary.envelopes[0].listedReferenceCount,1);
assert.equal(wrappedSummary.calls[0].modelOutput.observed,false,'a shared wrapper must not be misreported as a direct per-call output');
assert.equal(wrappedSummary.complete,false,'wrapper text does not invent missing structured results');
const excerpts=new WebSearchEvidence();
excerpts.observe(raw({type:'function_call',namespace:'web',name:'run',call_id:'excerpt',arguments:'{}'}));
excerpts.observe(raw({type:'function_call_output',call_id:'excerpt',output:'Web results. Excerpts are retrieved source text.\nSource URL: https://example.com/a\n原文摘录\nSource URL: https://example.com/b\n第二篇\nSome source text was unavailable or omitted by policy/output limits.\n'}));
const excerptSummary=await excerpts.save(await mkdtemp(path.join(os.tmpdir(),'web-excerpts-')));
assert.equal(excerptSummary.calls[0].listedSourceCount,2);
assert.equal(excerptSummary.calls[0].contentForm,'source-excerpts');
assert.equal(excerptSummary.calls[0].upstreamContentOmitted,true);
assert.equal(excerptSummary.calls[0].upstreamTruncated,'unknown','omission could also mean unavailability, not proven truncation');
assert.equal(excerptSummary.calls[0].recorderTruncated,false);
const nullOutput=new WebSearchEvidence();
nullOutput.observe(completed({type:'webSearch',id:'null-output',results:[],action:{type:'search'}}));
nullOutput.observe(raw({type:'function_call_output',call_id:'null-output',output:null}));
assert.equal((await nullOutput.save(await mkdtemp(path.join(os.tmpdir(),'web-null-output-')))).complete,false);
console.log('PASS: null/empty distinction, lossless bodies, stable artifacts, opaque fields, truncation uncertainty and no model-consumption overclaim.');
