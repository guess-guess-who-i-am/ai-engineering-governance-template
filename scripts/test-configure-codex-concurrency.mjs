import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, readdir, symlink, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { concurrencyConfig, configure } from './configure-codex-concurrency.mjs';

const original = '# preserve all unrelated text\nmodel = "unchanged"\n[features]\ncode_mode = true\nmulti_agent = false # repaired\n[hooks.state."existing"]\ntrusted_hash = "unchanged"\n[mcp_servers.example]\ncommand = "unchanged"\n';
const changed = concurrencyConfig(original);
assert.equal(changed.changes.length, 3);
assert.match(changed.text, /multi_agent = true # repaired/);
assert.match(changed.text, /\[agents\]\nenabled = true\nmax_concurrent_threads_per_session = 20/);
assert.equal(changed.text.replace('multi_agent = true # repaired', 'multi_agent = false # repaired').replace('\n[agents]\nenabled = true\nmax_concurrent_threads_per_session = 20\n', ''), original);
assert.deepEqual(concurrencyConfig(changed.text), { text: changed.text, changes: [] });
assert.equal(concurrencyConfig('[features]\r\nmulti_agent = false\r\n').text.replaceAll('\r\n', '').includes('\n'), false);
for (const width of [0, 21, 1.5, NaN]) assert.throws(() => concurrencyConfig(original, width));
for (const source of ['[features]\nmulti_agent=false\nmulti_agent=true\n', '[agents]\n[agents]\n', '[features]\nmulti_agent="false"\n']) assert.throws(() => concurrencyConfig(source));
const home = await mkdtemp(path.join(os.tmpdir(), 'codex-concurrency-test-'));
await mkdir(path.join(home, '.codex'));
const file = path.join(home, '.codex', 'config.toml');
await writeFile(file, original, { mode: 0o600 });
assert.equal((await configure({ home })).status, 'changes-required');
assert.equal(await readFile(file, 'utf8'), original, 'check is read-only');
assert.deepEqual(await readdir(path.dirname(file)), ['config.toml']);
const result = await configure({ home, apply: true });
assert.equal(result.status, 'configured');
assert.equal(await readFile(result.backup, 'utf8'), original);
assert.equal(await readFile(file, 'utf8'), changed.text);
assert.equal((await configure({ home, apply: true })).status, 'current');
await writeFile(`${file}.concurrency.lock`, '');
await assert.rejects(configure({ home, apply: true }), { code: 'EEXIST' });
const linkedHome = await mkdtemp(path.join(os.tmpdir(), 'codex-concurrency-link-'));
await mkdir(path.join(linkedHome, '.codex'));
await symlink(file, path.join(linkedHome, '.codex', 'config.toml'));
await assert.rejects(configure({ home: linkedHome, apply: true }), /regular file/);
console.log('PASS: narrow merge, unrelated settings/trust preserved, CRLF, limits, ambiguous input rejection, read-only check, backup, idempotency, lock and symlink protection.');
