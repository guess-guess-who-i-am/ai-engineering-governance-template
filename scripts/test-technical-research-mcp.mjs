import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { TechnicalResearch } from './technical-research.mjs';

const folder=await mkdtemp(path.join(os.tmpdir(),'technical-mcp-'));
await mkdir(folder,{recursive:true});
const fixture='model = "fixture"\n\n[mcp_servers.other]\ncommand = "preserve-other"\n';
await writeFile(path.join(folder,'config.toml'),fixture);
const installer=fileURLToPath(new URL('./install-technical-research.mjs',import.meta.url));
const install=()=>spawnSync(process.execPath,[installer,'--home',folder],{encoding:'utf8',windowsHide:true,env:{...process.env,CODEX_HOME:folder}});
const first=install();assert.equal(first.status,0,first.stderr);
const installed=await readFile(path.join(folder,'config.toml'),'utf8');assert(installed.startsWith(fixture.trimEnd()));
assert.equal((installed.match(/\[mcp_servers\.technical_research\]/g)||[]).length,1);
const second=install();assert.equal(second.status,0,second.stderr);assert.equal(await readFile(path.join(folder,'config.toml'),'utf8'),installed,'install must be idempotent');
const cacheDirectory=path.join(folder,'technical-research-cache');
const seed=new TechnicalResearch({cacheDirectory,fetchImpl:async()=>new Response(JSON.stringify({items:[{full_name:'owner/project',html_url:'https://github.com/owner/project',stargazers_count:2000}]}),{status:200,headers:{'content-type':'application/json'}})});
const queries=[{source:'github',query:'connection pooling'}];
await seed.batch({queries,cacheMode:'refresh'});
const fromStable=JSON.parse(first.stdout);assert(fromStable.entry.startsWith(path.join(folder,'tools','complementary-search')));
const checked=spawnSync(process.execPath,[installer,'--home',folder,'--check'],{encoding:'utf8',env:{...process.env,CODEX_HOME:folder}});
assert.equal(checked.status,0,checked.stderr);
const skillFile=path.join(folder,'.agents/skills/parallel-web-research/SKILL.md');
const skillBefore=await readFile(skillFile,'utf8');await writeFile(skillFile,skillBefore+'\ndrift\n');
const drift=spawnSync(process.execPath,[installer,'--home',folder,'--check'],{encoding:'utf8',env:{...process.env,CODEX_HOME:folder}});
assert.notEqual(drift.status,0);assert.equal(await readFile(skillFile,'utf8'),skillBefore+'\ndrift\n','check must not repair drift');
assert.equal(install().status,0);
const conflict=installed+'\n[mcp_servers.technical_research.env]\nSEARCH_TEST = "fixture"\n';
await writeFile(path.join(folder,'config.toml'),conflict);
const rejected=install();assert.notEqual(rejected.status,0);assert.match(rejected.stderr,/explicit migration/);
assert.equal(await readFile(path.join(folder,'config.toml'),'utf8'),conflict,'unsupported config must be preserved');
await writeFile(path.join(folder,'config.toml'),installed);
const transport=new StdioClientTransport({command:process.execPath,args:[fromStable.entry],cwd:os.tmpdir(),env:{...process.env,CODEX_HOME:folder},stderr:'pipe'});
const client=new Client({name:'technical-research-test',version:'1.0.0'});
try{
 await client.connect(transport);
 const tools=await client.listTools();assert.equal(tools.tools.length,2);assert.equal(tools.tools[0].name,'technical_research_batch');
 assert.equal(tools.tools[1].name,'complementary_search_batch');
 const badMixed=await client.callTool({name:'complementary_search_batch',arguments:{queries,unexpected:true}});
 assert.equal(badMixed.isError,true);assert.match(badMixed.content[0].text,/Unknown argument/);
 const advertised=tools.tools[0].inputSchema.properties.timeoutMs;
 const invalid=await client.callTool({name:'technical_research_batch',arguments:{queries,timeoutMs:45000}});
 assert.equal(invalid.isError,true);
 const validation=JSON.parse(invalid.content[0].text);
 assert.equal(validation.code,'INVALID_ARGUMENT');assert.equal(validation.field,'timeoutMs');
 assert.equal(validation.maximum,advertised.maximum);assert.equal(validation.minimum,advertised.minimum);
 const output=await client.callTool({name:'technical_research_batch',arguments:{queries,cacheMode:'only'}});
 assert.equal(output.isError,false);const result=JSON.parse(output.content[0].text);
 assert.equal(result.cacheHits,1);assert.equal(result.selected[0].title,'owner/project');
 assert.equal(result.operations[0].results,undefined,'full unscreened catalog must remain in artifacts');
 assert.equal(JSON.parse(await readFile(result.artifact,'utf8')).operations[0].results.length,1);
 const mixed=await client.callTool({name:'technical_research_batch',arguments:{queries:[...queries,{source:'github',query:'not cached'}],cacheMode:'only'}});
 assert.equal(mixed.isError,false,'usable partial evidence must not masquerade as an overall tool failure');
 const mixedResult=JSON.parse(mixed.content[0].text);
 assert.equal(mixedResult.status,'cache-miss');assert.equal(mixedResult.cacheHits,1);
 assert.equal(mixedResult.operations.filter(op=>op.status==='cache-miss').length,1);
 const missing=await client.callTool({name:'technical_research_batch',arguments:{queries:[{source:'github',query:'missing'}],cacheMode:'only'}});
 assert.equal(missing.isError,true);assert.equal(JSON.parse(missing.content[0].text).status,'cache-miss');
 const complement=await client.callTool({name:'complementary_search_batch',arguments:{queries,cacheMode:'only'}});
 const complementResult=JSON.parse(complement.content[0].text);
 assert.equal(complement.isError,false);assert.equal(complementResult.selected[0].title,'owner/project');
 assert.equal(complementResult.operations[0].branches.api.results,undefined,'raw branch candidates stay in artifacts');
 const chinese=await client.callTool({name:'complementary_search_batch',arguments:{queries:[{source:'github',query:'中文查询'}],cacheMode:'only'}});
 assert.equal(chinese.isError,true,'missing offline web cache must not silently network');
 console.log('PASS: installed standalone MCP handshake/tool execution, filtered context/raw evidence, no-network cache, idempotent install and check mode.');
}finally{await client.close();}
